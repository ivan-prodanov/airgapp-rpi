// apChannelRe accepts 1..165 — any digits up to 3 chars. The semantic
// validation (which band is this channel in?) happens in bandFor().
var apChannelRe = regexp.MustCompile(`^[0-9]{1,3}$`)

// bandFor maps an AP channel number to hostapd's hw_mode value. The
// split is purely a 2.4 vs 5 GHz question: channels 1-14 are 2.4 GHz,
// 36+ are 5 GHz. There's a gap (15-35) that's not allocated to either
// band — we reject it as invalid.
//
// Returning ("a", true) means 5 GHz. ("g", false) means 2.4 GHz.
// (_, _, err) means the channel isn't in either band.
func bandFor(channel int) (hwMode string, is5GHz bool, err error) {
	switch {
	case channel >= 1 && channel <= 14:
		return "g", false, nil
	case channel >= 36 && channel <= 165:
		return "a", true, nil
	default:
		return "", false, fmt.Errorf("channel %d isn't in any allocated 2.4 GHz (1-14) or 5 GHz (36-165) band", channel)
	}
}

type HotspotService struct {
	db       *sql.DB
	exec     *executor.Executor
	mu       sync.Mutex
	confPath string // hostapd.conf; tests point it at a temp file

	verifyFirewall func() error
	applyFirewall  func() error
}

func NewHotspotService(db *sql.DB, exec *executor.Executor) *HotspotService {
	return &HotspotService{db: db, exec: exec, confPath: "/etc/hostapd/hostapd.conf"}
}

// SetFirewallGate installs the airgap gate. Wired in services.New from
// FirewallService.Verify / .Apply. Kept as funcs rather than a service
// reference so hotspot_test can prove the refusal path without a database.
func (s *HotspotService) SetFirewallGate(verify func() error, apply func() error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.verifyFirewall = verify
	s.applyFirewall = apply
}

func (s *HotspotService) Apply() error {
	s.mu.Lock()
	defer s.mu.Unlock()

	settings := s.getSettings()

	// Sanitize user-supplied values before embedding in the config file —
	// newlines or control chars in SSID/passphrase would inject arbitrary
	// hostapd directives (wpa=0, macaddr_acl bypass, etc.).
	ssid := SanitizeSingleLine(settings["ap_ssid"])
	pass := SanitizeSingleLine(settings["ap_password"])
	channel := SanitizeSingleLine(settings["ap_channel"])
	country := SanitizeSingleLine(settings["ap_country"])
	if len(pass) < 8 {
		return fmt.Errorf("wpa_passphrase must be at least 8 chars after sanitisation")
	}
	if !apChannelRe.MatchString(channel) {
		return fmt.Errorf("invalid ap_channel %q", channel)
	}
	channelInt, err := strconv.Atoi(channel)
	if err != nil {
		return fmt.Errorf("ap_channel %q is not numeric: %w", channel, err)
	}
	hwMode, is5GHz, err := bandFor(channelInt)
	if err != nil {
		return err
	}
	// country_code is mandatory for 5 GHz (regulatory). For 2.4 GHz
	// it's optional but harmless. Default to "00" (worldwide, UNII-1
	// 5 GHz channels 36-48 allowed) if the operator hasn't set one.
	if country == "" {
		country = "00"
	}

	var b strings.Builder
	b.WriteString("# Generated by netfilterd — do not edit\n")
	b.WriteString("interface=wlan0\n")
	b.WriteString("driver=nl80211\n")
	fmt.Fprintf(&b, "ssid=%s\n", ssid)
	fmt.Fprintf(&b, "hw_mode=%s\n", hwMode)
	fmt.Fprintf(&b, "channel=%s\n", channel)
	fmt.Fprintf(&b, "country_code=%s\n", country)
	// ieee80211d advertises the country code in beacons (needed by
	// regulatory-strict clients to learn allowed channels). ieee80211n
	// enables HT/2.4-GHz wide channels. On 5 GHz we ALSO enable
	// ieee80211ac (VHT) for modern speeds and ieee80211h (DFS + TPC,
	// required if the operator later picks a DFS channel; harmless on
	// non-DFS channels like 36).
	b.WriteString("ieee80211d=1\n")
	b.WriteString("ieee80211n=1\n")
	if is5GHz {
		b.WriteString("ieee80211ac=1\n")
		b.WriteString("ieee80211h=1\n")
	}
	b.WriteString("wmm_enabled=1\n")
	b.WriteString("macaddr_acl=0\n")
	b.WriteString("auth_algs=1\n")
	b.WriteString("ignore_broadcast_ssid=0\n")
	b.WriteString("wpa=2\n")
	fmt.Fprintf(&b, "wpa_passphrase=%s\n", pass)
	b.WriteString("wpa_key_mgmt=WPA-PSK\n")
	b.WriteString("rsn_pairwise=CCMP\n")

	// The file holds the WPA passphrase: root only. WriteFile keeps an existing
	// file's mode, so set it explicitly too.
	confPath := s.confPath
	err = os.WriteFile(confPath, []byte(b.String()), 0600)
	if err == nil {
		err = os.Chmod(confPath, 0600)
	}
	if err != nil {
		if !s.exec.DryRun {
			return fmt.Errorf("write %s: %w", confPath, err)
		}
		log.Printf("[DRY-RUN] Would write %s", confPath)
	}

	if _, err := s.exec.Run("systemctl", "restart", "hostapd"); err != nil {
		return fmt.Errorf("restart hostapd: %w", err)
	}

	log.Printf("[HOTSPOT] Applied config: SSID=%s, channel=%s", settings["ap_ssid"], settings["ap_channel"])
	return nil
}

// SetEnabled starts or stops hostapd without touching its config.
//
// Deliberately NOT part of Apply(): Apply rewrites /etc/hostapd/hostapd.conf
// and restarts. This is called automatically by the lock watcher, potentially
// many times a day, and an automatic path that can rewrite the AP's config is a
// way to lose the AP permanently. This one can only change run state.
//
// Raising the AP is gated on the firewall being verifiably default-deny — and
// on a gate existing at all; LOWERING it never is, on any path. That asymmetry
// is the whole point — a firewall fault must not be able to leave the car
// online.
func (s *HotspotService) SetEnabled(up bool) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if up {
		// No gate installed is not "no checks needed" — it is a construction
		// site that forgot to wire one. Fail closed rather than raise an
		// ungated AP, which is the one thing this component exists to prevent.
		if s.verifyFirewall == nil {
			log.Printf("[HOTSPOT] REFUSING to raise the AP — no firewall gate installed")
			return fmt.Errorf("refusing to start hostapd: no firewall verify gate installed (SetFirewallGate was never called)")
		}
		if err := s.verifyFirewall(); err != nil {
			log.Printf("[HOTSPOT] firewall gate FAILED (%v) — reapplying before considering the AP", err)
			var applyErr error
			if s.applyFirewall == nil {
				applyErr = fmt.Errorf("no firewall apply hook installed, so the ruleset could not be repaired")
				log.Printf("[HOTSPOT] %v", applyErr)
			} else if aerr := s.applyFirewall(); aerr != nil {
				applyErr = fmt.Errorf("firewall reapply failed: %w", aerr)
				log.Printf("[HOTSPOT] %v", applyErr)
			}
			if verr := s.verifyFirewall(); verr != nil {
				// REFUSE. An offline car is recoverable; a car that reached
				// Tesla is not. Report the reapply failure alongside the
				// verify failure — the reapply is usually the real cause.
				log.Printf("[HOTSPOT] REFUSING to raise the AP — firewall still unverified: %v", verr)
				return fmt.Errorf("refusing to start hostapd over an unverified firewall: %w", errors.Join(verr, applyErr))
			}
			log.Printf("[HOTSPOT] firewall gate satisfied after reapply")
		}
	}

	action := "stop"
	if up {
		action = "start"
	}
	if _, err := s.exec.Run("systemctl", action, "hostapd"); err != nil {
		return fmt.Errorf("%s hostapd: %w", action, err)
	}
	log.Printf("[HOTSPOT] %s hostapd", action)
	return nil
}

func (s *HotspotService) getSettings() map[string]string {
	// Defaults bake V4's choice: 5 GHz channel 36 + worldwide regdomain.
	// This frees the 2.4 GHz radio for BLE on the Pi 4 (where WiFi and
	// BLE share one Broadcom chip and 2.4 GHz hostapd starves BLE scans).
	// Existing installs upgrade via setting ap_channel=36 + ap_country.
	defaults := map[string]string{
		"ap_ssid":     "NetFilter",
		"ap_password": "changeme123",
		"ap_channel":  "36",
		"ap_country":  "00",
	}

	rows, err := s.db.Query("SELECT key, value FROM settings WHERE key IN ('ap_ssid', 'ap_password', 'ap_channel', 'ap_country')")
	if err != nil {
		// Don't silently write a default-passwd hostapd.conf — surface
		// the DB failure so an operator notices instead of booting an
		// AP with the seed password.
		log.Printf("[HOTSPOT] read settings: %v — falling back to defaults", err)
		return defaults
	}
	defer rows.Close()

	for rows.Next() {
		var k, v string
		if err := rows.Scan(&k, &v); err != nil {
			log.Printf("[HOTSPOT] scan setting row: %v", err)
			continue
		}
		defaults[k] = v
	}
	return defaults
}
